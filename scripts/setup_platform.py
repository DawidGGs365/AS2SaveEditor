#!/usr/bin/env python3
"""Create and configure a platform folder (android/ios/linux/macos/windows/web).

    python scripts/setup_platform.py <platform|all> [--clean] [--no-icons] [--no-patches] [--no-pub]

Steps: `flutter create` for the platform -> patches/<platform>/*.patch (git apply)
-> patches/<platform>/overlay/** (copied over) -> patches/<platform>/*.py (hooks)
-> icons from icons/ -> `flutter pub get`.
Placeholders @ORG@ @NAME@ @DISPLAY_NAME@ @DESCRIPTION@ are expanded in patches and overlay files.
"""
import argparse, json, os, re, shutil, subprocess, sys, tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PLATFORMS = ["android", "ios", "linux", "macos", "windows", "web"]


def cfg():
    c = json.loads((ROOT / "scripts" / "config.json").read_text(encoding="utf-8"))
    pub = (ROOT / "pubspec.yaml").read_text(encoding="utf-8")
    c["name"] = re.search(r"^name:\s*(\S+)", pub, re.M).group(1)
    return c


def subst(text, c):
    for k, v in (("@ORG@", c["org"]), ("@NAME@", c["name"]),
                 ("@DISPLAY_NAME@", c["display_name"]), ("@DESCRIPTION@", c["description"])):
        text = text.replace(k, v)
    return text


class SetupError(Exception):
    pass


def run(cmd, **kw):
    print("+", " ".join(map(str, cmd)))
    subprocess.run(cmd, check=True, cwd=ROOT, **kw)


def flutter():
    exe = shutil.which("flutter")
    if not exe:
        sys.exit("flutter not found in PATH")
    try:
        out = subprocess.run([exe, "--version", "--machine"], capture_output=True, text=True, check=True).stdout
        have = json.loads(out[out.index("{"):])["frameworkVersion"]
        want = (ROOT / ".flutter-version").read_text().strip()
        if have != want:
            print(f"WARNING: Flutter {have} installed, patches are made for {want}; a patch may fail to apply.")
    except Exception:
        pass
    return exe


def apply_patch(path, c):
    text = subst(path.read_text(encoding="utf-8").replace("\r\n", "\n"), c)
    with tempfile.TemporaryDirectory() as d:
        tmp = Path(d) / path.name
        tmp.write_bytes(text.encode("utf-8"))
        try:
            run(["git", "apply", "--whitespace=nowarn", "--ignore-whitespace", "-p1", str(tmp)])
        except subprocess.CalledProcessError:
            raise SetupError(f"Patch {path.relative_to(ROOT)} does not apply to the generated template "
                             f"(Flutter version changed?). Regenerate it, see patches/README.md.")


def setup(plat, a, c, fl):
    pdir = ROOT / plat
    marker = pdir / ".platform-setup"
    if a.clean and pdir.exists():
        shutil.rmtree(pdir)
    if marker.exists():
        print(f"[{plat}] already set up (use --clean to redo)")
        return
    if pdir.exists():
        raise SetupError(f"{plat}/ exists but was not made by this script; delete it or use --clean.")
    print(f"== {plat}")
    try:
        generate(plat, a, c, fl, pdir, marker)
    except (SetupError, subprocess.CalledProcessError, OSError):
        shutil.rmtree(pdir, ignore_errors=True)  # don't leave a half-configured folder behind
        raise


def generate(plat, a, c, fl, pdir, marker):
    had_widget_test = (ROOT / "test" / "widget_test.dart").exists()
    run([fl, "create", "--platforms", plat, "--project-name", c["name"], "--org", c["org"], "--no-pub", "."])
    if not had_widget_test:  # template test references MyApp, which this project doesn't have
        (ROOT / "test" / "widget_test.dart").unlink(missing_ok=True)
    base = ROOT / ".platform-base" / plat  # pristine copy, used by save_patch.py
    shutil.rmtree(base, ignore_errors=True)
    shutil.copytree(pdir, base)

    pp = ROOT / "patches" / plat
    if not a.no_patches:
        for p in sorted(pp.glob("*.patch")):
            apply_patch(p, c)
        ov = pp / "overlay"
        if ov.is_dir():
            for f in sorted(x for x in ov.rglob("*") if x.is_file()):
                dst = ROOT / f.relative_to(ov)
                dst.parent.mkdir(parents=True, exist_ok=True)
                try:
                    dst.write_text(subst(f.read_text(encoding="utf-8"), c), encoding="utf-8", newline="\n")
                except UnicodeDecodeError:
                    shutil.copyfile(f, dst)
        env = dict(os.environ, PROJECT_ROOT=str(ROOT), PLATFORM=plat, ORG=c["org"], PROJECT_NAME=c["name"],
                   DISPLAY_NAME=c["display_name"], DESCRIPTION=c["description"])
        for h in sorted(pp.glob("*.py")):
            run([sys.executable, str(h)], env=env)
    if not a.no_icons:
        run([sys.executable, str(ROOT / "scripts" / "make_icons.py"), plat])
    marker.write_text("generated by scripts/setup_platform.py\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("platform", choices=PLATFORMS + ["all"])
    ap.add_argument("--clean", action="store_true", help="delete and regenerate the platform folder")
    ap.add_argument("--no-icons", action="store_true")
    ap.add_argument("--no-patches", action="store_true")
    ap.add_argument("--no-pub", action="store_true")
    a = ap.parse_args()
    c, fl = cfg(), flutter()
    if not a.no_pub:  # first, so the IDE/analyzer works even if a platform step fails below
        run([fl, "pub", "get"])
    failed = {}
    for p in (PLATFORMS if a.platform == "all" else [a.platform]):
        try:
            setup(p, a, c, fl)
        except (SetupError, subprocess.CalledProcessError, OSError) as e:
            failed[p] = e
            print(f"\n!! {p} failed: {e}\n", file=sys.stderr)
    if failed:
        sys.exit("Failed platforms: " + ", ".join(failed) + " (their folders were removed; fix and rerun)")


if __name__ == "__main__":
    main()
